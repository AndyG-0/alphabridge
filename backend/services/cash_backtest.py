"""Backtest of the cash-deployment rule on Damodaran's annual stock/bill/inflation history (data/historical_returns.json).

Annual data has no VIX, P/E or 200-day average, so the full `deployment_score` cannot be replayed. This tests a reduced score
built only from what the data holds (real cash yield and the prior year's stock return as a stand-in for "below the 200-day
average"), run through the same thresholds and deploy-fraction rule as the live engine. See docs/cash_backtest.md."""

import json
import statistics
from pathlib import Path

from services import cash_optimizer as co

HIST = Path(__file__).resolve().parents[1] / "data" / "historical_returns.json"
DOC = Path(__file__).resolve().parents[2] / "docs" / "cash_backtest.md"


def history() -> dict[int, dict]:
    return {int(y): v for y, v in json.loads(HIST.read_text())["years"].items()}


def lite_score(bills: float, inflation: float, prior_stock_return: float) -> float:
    """Half real-yield hurdle, half prior-year drawdown. Same scaling as `deployment_score`'s matching components."""
    s_real = 100 - co._scale(bills - inflation, -0.01, 0.03)
    s_dd = co._scale(-prior_stock_return, -0.05, 0.15)
    return 0.5 * s_real + 0.5 * s_dd


def _run(hist: dict[int, dict], start: int, years: int, mode: str, dca_frac: float) -> float:
    """Ending value of 1.0 of starting cash. Cash earns bills; deployed money stays in stocks (the live engine never sells)."""
    cash, stocks = 1.0, 0.0
    if mode == "LUMP":
        cash, stocks = 0.0, 1.0
    for y in range(start, start + years):
        h = hist[y]
        if mode == "SIGNAL":
            prior = hist[y - 1]
            f = co.deploy_fraction(lite_score(prior["bills"], prior["inflation"], prior["stocks"]))
        elif mode == "NAIVE_DCA":
            f = dca_frac
        else:
            f = 0.0
        moved = cash * f
        cash, stocks = cash - moved, stocks + moved
        cash *= 1 + h["bills"]
        stocks *= 1 + h["stocks"]
    return cash + stocks


MODES = {
    "SIGNAL": "Deployment rule (reduced score)",
    "NAIVE_DCA": "Naive DCA (fixed share of remaining cash each year)",
    "LUMP": "Buy-and-hold stocks from day one",
    "CASH": "Stay in T-bills",
}


def run(window: int = 10, first_year: int = 1930, dca_frac: float = 0.25) -> dict:
    hist = history()
    last = max(hist)
    starts = [y for y in range(first_year, last - window + 2) if y - 1 in hist]
    res: dict[str, list[float]] = {m: [] for m in MODES}
    for s in starts:
        for m in MODES:
            res[m].append(_run(hist, s, window, m, dca_frac))
    lump = res["LUMP"]
    out = []
    for m, label in MODES.items():
        v = res[m]
        out.append(
            {
                "mode": m,
                "label": label,
                "median_multiple": statistics.median(v),
                "mean_multiple": statistics.fmean(v),
                "worst_multiple": min(v),
                "best_multiple": max(v),
                "beats_lump_pct": sum(1 for a, b in zip(v, lump, strict=True) if a > b) / len(v),
                "beats_cash_pct": sum(1 for a, b in zip(v, res["CASH"], strict=True) if a > b) / len(v),
                "loses_money_pct": sum(1 for a in v if a < 1.0) / len(v),
            }
        )
    return {"window_years": window, "windows": len(starts), "first_start": starts[0], "last_start": starts[-1], "results": out}


def render_markdown() -> str:
    cfg = json.loads((Path(__file__).resolve().parents[1] / "data" / "cash_rules.json").read_text())["backtest"]
    r = run(cfg["window_years"], cfg["first_year"], cfg["naive_dca_fraction"])
    lines = [
        "# Cash-deployment backtest",
        "",
        "_Generated by `services/cash_backtest.render_markdown()`; `tests/test_cash_backtest.py` fails if this file is stale._",
        "",
        f"Source: Damodaran annual returns ({cfg['source_url']}), via `data/historical_returns.json`.",
        "",
        "## Method",
        "",
        f"- {r['windows']} overlapping {r['window_years']}-year windows, starting {r['first_start']}–{r['last_start']}. Each starts with 1.00 in cash.",
        "- Cash earns the T-bill return; deployed money earns the S&P 500 total return and is never sold (as in the live engine).",
        "- **Signal**: each January the rule deploys a share of the remaining cash chosen by a *reduced* score — 50% real cash yield "
        "(bills minus inflation), 50% prior-year stock return as a stand-in for 'below the 200-day average' — using the live engine's "
        "thresholds (HOLD under 45, DCA 45–70, aggressive above 70) and `cash_optimizer.deploy_fraction`.",
        f"- **Naive DCA**: deploy {cfg['naive_dca_fraction']:.0%} of remaining cash every year regardless of signals.",
        "- Compared with buying stocks on day one and with staying in bills. Multiples are ending value per 1.00 invested, pre-tax and pre-fee.",
        "",
        "## Results",
        "",
        "| Strategy | Median | Mean | Worst | Best | Beats lump sum | Beats cash | Loses money |",
        "|---|---|---|---|---|---|---|---|",
    ]
    lines.extend(
        f"| {x['label']} | {x['median_multiple']:.2f}x | {x['mean_multiple']:.2f}x | {x['worst_multiple']:.2f}x | {x['best_multiple']:.2f}x "
        f"| {x['beats_lump_pct']:.0%} | {x['beats_cash_pct']:.0%} | {x['loses_money_pct']:.0%} |"
        for x in r["results"]
    )
    lines += [
        "",
        "## What this does and does not show",
        "",
        "- It cannot validate the live score: VIX, the earnings yield and the 200-day average are not in annual data, so the ERP and fear "
        "components (70% of the live weight) are absent.",
        "- Annual steps hide intra-year timing; the prior-year return is a coarse drawdown proxy.",
        "- Overlapping windows are not independent samples, so percentages overstate how much evidence there is.",
        "- A deployment rule trades some expected return for lower regret and smaller drawdowns; read 'Worst' and 'Loses money' alongside the medians.",
        "- Nothing here is a forecast; it is the history of one rule on one index.",
        "",
    ]
    return "\n".join(lines)
